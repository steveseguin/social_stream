'use strict';
const {app,BrowserWindow,session}=require('electron');
const fs=require('fs'),path=require('path'),os=require('os'),http=require('http'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const catalogCount=JSON.parse(fs.readFileSync(path.join(root,'docs/data/overlay-gallery.json'),'utf8')).length;
const output=fs.mkdtempSync(path.join(os.tmpdir(),'ssn-gallery-ui-'));
app.setPath('userData',path.join(output,'profile'));
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const server=http.createServer((req,res)=>{
  const file=path.resolve(root,'.'+decodeURIComponent(new URL(req.url,'http://localhost').pathname));
  if(!file.startsWith(root+path.sep)||!fs.existsSync(file)||!fs.statSync(file).isFile()){res.statusCode=404;return res.end();}
  res.setHeader('Content-Type',({'.html':'text/html','.css':'text/css','.js':'text/javascript','.json':'application/json','.webp':'image/webp','.svg':'image/svg+xml'})[path.extname(file)]||'application/octet-stream');
  fs.createReadStream(file).pipe(res);
});
app.whenReady().then(async()=>{
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const base='http://127.0.0.1:'+server.address().port;
  session.defaultSession.webRequest.onBeforeRequest((d,cb)=>cb({cancel:!d.url.startsWith(base)&&!d.url.startsWith('data:')}));
  const win=new BrowserWindow({show:false,width:1400,height:1000,webPreferences:{offscreen:true,backgroundThrottling:false,contextIsolation:true,nodeIntegration:false}});
  const run=code=>win.webContents.executeJavaScript(code);
  await win.loadURL(base+'/docs/overlay-gallery.html');
  await delay(900);
  assert.strictEqual(await run('document.querySelectorAll(".gallery-card").length'),catalogCount);
  assert((await run('document.getElementById("gallery-count").textContent')).includes(catalogCount+' of '+catalogCount));
  assert(await run('Array.from(document.querySelectorAll(".gallery-preview img")).slice(0,3).every(i=>i.complete&&i.naturalWidth>0)'));
  fs.writeFileSync(path.join(output,'desktop.png'),(await win.webContents.capturePage()).toPNG());
  await run('document.getElementById("gallery-search").value="Cat Cafe"; document.getElementById("gallery-search").dispatchEvent(new Event("input"));');
  assert.strictEqual(await run('document.querySelectorAll(".gallery-card:not([hidden])").length'),3);
  await run('document.querySelector("[data-category=featured]").click();');
  assert.strictEqual(await run('document.querySelectorAll(".gallery-card:not([hidden])").length'),1);
  await run('document.querySelector(".gallery-card:not([hidden]) [data-screenshot]").click();');
  assert(await run('!document.getElementById("gallery-lightbox").hidden && document.activeElement.id==="gallery-close"'));
  await run('document.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape"}));');
  assert(await run('document.getElementById("gallery-lightbox").hidden && document.activeElement.hasAttribute("data-screenshot")'));
  await run('document.querySelector(".gallery-card:not([hidden]) .gallery-open").click();');
  assert(await run('document.getElementById("gallery-setup").open && document.activeElement.id==="gallery-session"'));
  await run('document.getElementById("gallery-session").value="test & room"; document.getElementById("gallery-password").value="pa&ss=+#"; document.getElementById("gallery-password").dispatchEvent(new Event("input"));');
  const href=await run('document.querySelector(".gallery-card:not([hidden]) .gallery-open").href');
  const url=new URL(href);
  assert.strictEqual(url.searchParams.get('session'),'test & room');
  assert.strictEqual(url.searchParams.get('password'),'pa&ss=+#');
  assert.strictEqual(url.searchParams.get('style'),'cats');
  assert(!await run('location.search.includes("room")'));
  await run('document.getElementById("gallery-search").value="no-such-overlay-xyz"; document.getElementById("gallery-search").dispatchEvent(new Event("input"));');
  assert(await run('!document.getElementById("gallery-empty").hidden'));
  await run('document.getElementById("gallery-search").value=""; document.querySelector("[data-category=all]").click(); document.getElementById("gallery-setup").open=false; document.getElementById("gallery-theme").click(); window.scrollTo(0,0);');
  win.setSize(390,844);
  await delay(500);
  assert(await run('document.documentElement.scrollWidth<=innerWidth+1'));
  assert(await run('(() => {const r=document.querySelector(".gallery-topbar nav").getBoundingClientRect(); return r.left>=0 && r.right<=innerWidth+1;})()'));
  const columns=await run('getComputedStyle(document.querySelector(".gallery-grid")).gridTemplateColumns');
  assert.strictEqual(columns.split(' ').length,1);
  fs.writeFileSync(path.join(output,'mobile.png'),(await win.webContents.capturePage()).toPNG());
  // Matching sets share credentials, never open connections until a link is followed.
  assert.strictEqual(await run('document.querySelectorAll(".gallery-use-set:not([hidden])").length'),24);
  await run('document.getElementById("gallery-session").value=""; document.getElementById("gallery-session").dispatchEvent(new Event("input")); document.querySelector("[data-collection=cat] .gallery-use-set").click();');
  assert(await run('document.getElementById("gallery-setup").open && document.activeElement.id==="gallery-session"'));
  assert.strictEqual(await run('document.querySelectorAll(".gallery-set-row button:disabled").length'),3);
  assert.strictEqual(await run('document.querySelectorAll(".gallery-set-row a[href]").length'),0);
  await run('document.getElementById("gallery-session").value="set & room"; document.getElementById("gallery-password").value="pa&ss=+#"; document.getElementById("gallery-session").dispatchEvent(new Event("input"));');
  for(const key of ['cat','dog','halloween','christmas','music','forest','space','dragon']) {
    await run('document.querySelector("[data-collection='+key+'] .gallery-use-set").click();');
    assert(await run('document.activeElement.id==="gallery-matching-title"'));
    const links=await run('Array.from(document.querySelectorAll(".gallery-set-row")).map(r=>({kind:r.dataset.kind,url:r.querySelector("input").value,href:r.querySelector("a").href}))');
    assert.strictEqual(links.length,3);
    for(const link of links) {
      const target=new URL(link.url);
      assert.strictEqual(link.url,link.href);
      assert.strictEqual(target.searchParams.get('session'),'set & room');
      assert.strictEqual(target.searchParams.get('password'),'pa&ss=+#');
      assert(!target.searchParams.has('staticart'));
      if(link.kind==='alerts')for(const type of ['follow','sub','dono','bits','raid','auction','hype'])assert.strictEqual(target.searchParams.get(type+'style'),'art-'+key);
      else assert.strictEqual(target.searchParams.get('style'),'art-'+key);
    }
  }
  await run('document.getElementById("gallery-set-motion").click();');
  assert(await run('Array.from(document.querySelectorAll(".gallery-set-row input")).every(i=>new URL(i.value).searchParams.has("staticart"))'));
  await run('document.querySelector("[data-collection=cat] .gallery-use-set").click();');
  assert(await run('Array.from(document.querySelectorAll(".gallery-set-row input")).every(i=>new URL(i.value).searchParams.has("staticart"))'));
  await run('document.getElementById("gallery-set-motion").click();document.getElementById("gallery-password").value="";document.getElementById("gallery-password").dispatchEvent(new Event("input"));');
  assert(await run('Array.from(document.querySelectorAll(".gallery-set-row input")).every(i=>!new URL(i.value).searchParams.has("staticart")&&!new URL(i.value).searchParams.has("password"))'));
  // Exercise clipboard success and rejection without altering the user's clipboard.
  await run('window.copiedSetLink="";Object.defineProperty(navigator,"clipboard",{configurable:true,value:{writeText:function(value){window.copiedSetLink=value;return Promise.resolve();}}});document.querySelector(".gallery-set-row button").click();');
  await delay(50);
  assert(await run('window.copiedSetLink===document.querySelector(".gallery-set-row input").value && document.getElementById("gallery-set-status").textContent==="Link copied."'));
  await run('navigator.clipboard.writeText=function(){return Promise.reject(new Error("denied"));};document.execCommand=function(){return false;};document.querySelector(".gallery-set-row button").click();');
  await delay(50);
  assert(await run('document.activeElement===document.querySelector(".gallery-set-row input") && document.activeElement.selectionEnd===document.activeElement.value.length'));
  assert(await run('document.getElementById("gallery-set-status").textContent.includes("Ctrl+C")'));
  await run('document.getElementById("gallery-session").dispatchEvent(new Event("input"));document.getElementById("gallery-matching").scrollIntoView({block:"start"});');
  await delay(400);
  assert(await run('document.documentElement.scrollWidth<=innerWidth+1'));
  assert(await run('Array.from(document.querySelectorAll(".gallery-set-row img")).every(i=>i.complete&&i.naturalWidth>0)'));
  fs.writeFileSync(path.join(output,'matching-mobile.png'),(await win.webContents.capturePage()).toPNG());
  win.setSize(320,740);await delay(200);
  assert(await run('document.documentElement.scrollWidth<=innerWidth+1'));
  assert(await run('Array.from(document.querySelectorAll(".gallery-set-row")).every(r=>r.scrollWidth<=r.clientWidth+1)'));
  win.setSize(1400,1000);
  await run('document.getElementById("gallery-setup").scrollIntoView({block:"start"});');await delay(400);
  fs.writeFileSync(path.join(output,'matching-desktop.png'),(await win.webContents.capturePage()).toPNG());
  await run('document.getElementById("gallery-theme").click();');await delay(200);
  fs.writeFileSync(path.join(output,'matching-dark.png'),(await win.webContents.capturePage()).toPNG());
  assert(!await run('location.search.includes("room")'));
  assert(await run('Object.keys(localStorage).every(k=>!(/session|password/i.test(k)))'));
  console.log('PASS matching sets: eight themes, three links, credentials, motion, copy/fallback, focus and responsive previews');
  console.log('PASS gallery filters, search, images, modal keyboard/focus, encoded links, empty state, theme and mobile layout');
  console.log('Screenshots: '+output);
  win.destroy();server.close();app.exit(0);
}).catch(error=>{console.error(error);app.exit(1);});
